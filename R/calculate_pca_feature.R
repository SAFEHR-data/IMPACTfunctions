calculate_pca_feature <- function(dataset,
                                  pca_hourly,
                                  preproccess = TRUE,
                                  filter_medication, # vector of medications names to include
                                  timeframe = c("whole_mar", "pre_op", "post_op", "custom"),
                                  t0 = NA,
                                  t_int = NA,
                                  t1 = NA,
                                  format,
                                  feature,
                                  feature_name){

  if(preproccess){
    pca_hourly = preproccess_pca_hourly(pca_hourly)
  }

  if(!missing(filter_medication)){
    pca_hourly %>% filter(simple_generic_name !in! filter_medication)
    if(nrow(pca_hourly)==0){
      cli::cli_abort("FIltered out all the rows, please check {.arg filter_medication} are valid")
    }
  }

  ## Assigning time points if used time frame argument
  if(missing(timeframe)){
    if(verbose){cli::cli_alert_success("No timeframe provided, searching whole MAR per encounter.")}
    timeframe <- "whole_mar"
  }else if(timeframe == "whole_mar"){
    if(verbose){cli::cli_alert_success("{.arg timeframe} set to {.val {timeframe}}, searching whole MAR per encounter.")}
  }else if(timeframe == "pre_op"){
    if(verbose){cli::cli_alert_success("{.arg timeframe} set to {.val {timeframe}}, searching only pre-operative period.")}
    t0_col <- dataset %>% select(.data[[joining_column]], t0 = admission_date)
    t1_col <- dataset %>% select(.data[[joining_column]], t1 = operation_date)
    timeframe_df <- inner_join(t0_col, t1_col) %>% collect()
  }else if(timeframe == "post_op"){
    if(verbose){cli::cli_alert_success("{.arg timeframe} set to {.val {timeframe}}, searching only post-operative period.")}
    t0_col <- dataset %>% select(.data[[joining_column]], t0 = operation_date)
    t1_col <- dataset %>% select(.data[[joining_column]], t1 = discharge_date)
    timeframe_df <- inner_join(t0_col, t1_col) %>% collect()
  }else if(timeframe == "custom"){
    ## Error checking that the timestamps are set properly
    if(verbose){cli::cli_alert_success("{.arg timeframe} set to {.val {timeframe}}, searching custom time period.")}
    #If timeframe custom, ensure propry t0,t1 and t_int set.
    if(!is.na(t_int) & !is.na(t1)){
      cli::cli_abort("You have tried to supply both a time interval ({.arg t_int}) and a end time ({.arg t_1}). \n \n Supply only one end time variable")
    }else if( !is.na(t0) & is.na(t1) & is.na(t_int) ){
    cli::cli_abort("Error: you have supplied a {.arg t0} to subset by but not {.arg t_int} or {.arg t1}. Please provide one or change the {.arg timeframe} argument")
    }

    #Assuming test above are passed then we can check if have passed a t_int and then calcualte the t_1
    if(!is.na(t_int)){

      timeframe_df <- dataset %>%
        select(.data[[joining_column]], t0 = all_of(t0)) %>%
        collect() %>%
        mutate(
          # Perform R-side arithmetic, then force UTC to match the Arrow schema
          t1 = lubridate::with_tz(t0 + t_int, tzone = "Etc/UTC")
        )

    }else if(!is.na(t1)){
      timeframe_df <- dataset %>% select(.data[[joining_column]],,  t0 = all_of(t0), t1 = all_of(t1))
    }else{
      cli::cli_abort("Hmm, you should not have been able to trigger this error message. Please {.href [leave a issue on the github](https://github.com/SAFEHR-data/IMPACTfunctions/issues)} called: \"Check timeframe logic of extract_medications()\ \n \n ")
      }

  }else{
    cli::cli_abort("Incorrect value supplied to {.arg timeframe}. See {.code ?extract_medication} for assistance. ")

  }


  if(timeframe == "whole_mar"){
    pca_hourly <- pca_hourly
  }else{
    #We need unique row indexes to do our filtering. Arrow doesnt support row indexing (by its nature of parrallel reading, etc).
    ##Instead we pull our timepoints in the logic section above to make a fixed dataset object where the t0 and t1 times are on the same row as the CSN.

    ## Rgrettably the arrow dpplyr doesnt have the kernals to deal with timeframe periods (as generated by t0 + t_int), thus we now call into memory.
    pca_hourly <- left_join(pca_hourly, timeframe_df, copy = TRUE, relationship = "one-to-many")
    pca_hourly <- pca_hourly %>% filter(time_hourly_start > t0) %>% filter(time_hourly_end < t1)
    if(verbose){cli::cli_alert_success("Removing Medications given outside of specified timeframe")}
  }

  csn_vector <- dataset %>% pull(.data[[csn_vector_name]]) %>% na.omit()

  if(feature == "binary"){

    MAR_df <- MAR %>% collect()

    result <-  data.frame(csn_vector) %>%
      mutate(match_status = csn_vector %in% MAR_df[[csn_vector_name]])


  }else if(feature == "sum_dose"){

    if((length(unique(MAR %>% pull(simple_generic_name))) > 1) | (length(unique(MAR %>% pull(route_simple))) > 1)){
      cli::cli_alert_danger("DANGER: The MAR supplied more than 1 medication or more than 1 route in it but your are requesting a summed dose. This may return a sum acorss different medications or routes.\n \n Consdier revising the arguement {.arg medication} in the {.fn extract_medication} function. (There may be situations when you want to proceed, such if you wanted to sum the total paracetmol doses regardless of route")
    }

    result <- MAR %>% group_by(.data[[csn_vector_name]]) %>%
      summarise(result = sum(dose, na.rm = FALSE)) %>%
      collect()

  }else if(feature == "sum_ome"){

    # If requesting and OME, check there is more than one medication

    if(length(unique(MAR %>% pull(simple_generic_name))) == 1){
      cli::cli_alert_danger("DANGER: The MAR supplied only has 1 medication in it but your are requesting and OME.\n \n Consdier remvoing the arguement {.arg medication} in the {.fn extract_medication} function. (There may be situations when you want to proceed, such as if you want to calcualute a OME of IV and Oral morphine. ")
    }

    result <- MAR %>% group_by(.data[[csn_vector_name]]) %>%
      summarise(result = sum(ome, na.rm = TRUE)) %>%
      collect()

  }

  names(result) <- c(csn_vector_name, feature_name)

  if(format == "table"){
    return(result)
  }else if (format == "joined"){
    return(left_join(dataset, result))
  }

}

preproccess_pca_hourly <- function(pca_hourly,
                                   route_dict = dictionary_medication_route,
                                   opioid_dict = dictionary_opioid,
                                   equivelence_dict = dictionary_equivelence
){

  # Check col names match
  if(! identical(names(route_dict), names(dictionary_medication_route))){cli::cli_abort("You have passed a custom dict to {.arg route_dict} but the column names don't match. \n \n Change the column names of your custom dict to {.val {paste0(names(dictionary_medication_route), collapse = ', ')}}")}
  if(! identical(names(opioid_dict), names(dictionary_opioid))){cli::cli_abort("You have passed a custom dict to {.arg opioid_dict} but the column names don't match. \n \n Change the column names of your custom dict to {.val {paste0(names(dictionary_opioid), collapse = ', ')}}")}
  if(! identical(names(equivelence_dict), names(dictionary_equivelence))){cli::cli_abort("You have passed a custom dict to {.arg equivelence_dict} but the column names don't match. \n \n Change the column names of your custom dict to {.val {paste0(names(dictionary_equivelence), collapse = ', ')}}")}

  # Check for pre-proccess mar already
  if(all(! names(pca_hourly) %in% c("route_simple", "opioid_name","equivelence"))){
    NULL
  }else{
    cli::cli_abort("{.val pca_hourly} passed to arguement {.arg pca_hourly} has columns from the dictonaries already \n \n Have you preproccessed it already?")
  }

  ## Note, we currently only have support for PCA delivered IV. This means we cannot add PCEA and the opioid equivelence therein.
  ## WE will add and error check and then a forced conversion.

  if(any(names(pca_hourly) %in% c("administration_route"))){
    cli::cli_abort("Columns {.val {c('administration_route')}} found in the {.arg pca_hourly}. \n Currently the function unable to handle this. ")
  }

  pca_hourly <- pca_hourly %>%
    mutate(administration_route = "Intravenous") %>%
    left_join(route_dict, by = "administration_route") %>%
    left_join(opioid_dict) %>%
   left_join(equivelence_dict)


  if(all(unique(pca_hourly$units) != "mg")){
    cli::cli_alert_danger("Not all units are in MG. Corcering mcg to mg and any NA to mg. ")

    pca_hourly <- pca_hourly %>%
      mutate(dose = case_when(
        units == "mcg" ~ dose_best_estimate_hourly/1000,
        .default = dose_best_estimate_hourly
      )) %>%
      mutate(units = "mg")

    }

  pca_hourly <- pca_hourly %>%
    mutate(ome = dose * equivelence) %>%
    select(mrn, admission_csn, simple_generic_name, dose, units, ome, time_hourly_start, time_hourly_end)

  return(pca_hourly)

}
